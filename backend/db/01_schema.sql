-- =============================================================================
-- XLearn LMS - Schema khởi tạo
-- Target chính : PostgreSQL 13+
-- Nguyên tắc   : chỉ dùng SQL chuẩn (ANSI) để dễ chuyển sang DBMS khác:
--   * Không dùng ENUM, ARRAY, JSONB, trigger, stored function, extension.
--   * Giá trị liệt kê = VARCHAR + CHECK (thêm giá trị mới chỉ cần sửa CHECK).
--   * Khóa chính BIGINT IDENTITY (SQL:2003) - xem README để map sang MySQL/SQL Server.
--   * Thời gian lưu TIMESTAMP WITH TIME ZONE, quy ước luôn ghi UTC.
--   * updated_at do tầng ứng dụng/ORM cập nhật (không dựa vào trigger).
--   * File (video/pdf/ảnh) KHÔNG lưu trong DB, chỉ lưu metadata + object key
--     trỏ tới object storage ngoài (S3 / MinIO / GCS / Azure Blob).
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. NGƯỜI DÙNG & PHÂN QUYỀN
-- -----------------------------------------------------------------------------
CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(255)  NOT NULL,
    password_hash   VARCHAR(255)  NOT NULL,
    full_name       VARCHAR(150)  NOT NULL,
    avatar_url      VARCHAR(1000),
    status          VARCHAR(20)   NOT NULL DEFAULT 'active',
    last_login_at   TIMESTAMP WITH TIME ZONE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_users_email      UNIQUE (email),
    -- Ứng dụng chuẩn hóa email về chữ thường -> UNIQUE thường là đủ, không cần index biểu thức
    CONSTRAINT ck_users_email_lower CHECK (email = LOWER(email)),
    CONSTRAINT ck_users_status     CHECK (status IN ('active', 'inactive', 'locked'))
);

-- Bảng tra cứu vai trò: thêm vai trò mới (admin, assistant...) = INSERT, không cần ALTER
CREATE TABLE roles (
    id          SMALLINT     NOT NULL PRIMARY KEY,
    code        VARCHAR(30)  NOT NULL,
    name        VARCHAR(100) NOT NULL,
    CONSTRAINT uq_roles_code UNIQUE (code)
);

-- Một user có thể có nhiều vai trò (vd: vừa là giảng viên vừa là học viên)
CREATE TABLE user_roles (
    user_id     BIGINT   NOT NULL,
    role_id     SMALLINT NOT NULL,
    granted_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_user_roles PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_user_roles_role FOREIGN KEY (role_id) REFERENCES roles (id)
);
CREATE INDEX ix_user_roles_role ON user_roles (role_id);

-- -----------------------------------------------------------------------------
-- 2. OBJECT STORAGE (metadata của file nằm ngoài DB)
--    URL thực tế (presigned URL / CDN URL) do backend sinh lúc runtime từ
--    provider + bucket + object_key -> đổi CDN/provider không phải sửa dữ liệu.
-- -----------------------------------------------------------------------------
CREATE TABLE storage_objects (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider            VARCHAR(20)   NOT NULL,          -- s3 | minio | gcs | azure
    bucket              VARCHAR(255)  NOT NULL,
    object_key          VARCHAR(1024) NOT NULL,          -- vd: courses/12/lessons/34/video.mp4
    original_filename   VARCHAR(255),
    content_type        VARCHAR(100)  NOT NULL,          -- MIME: video/mp4, application/pdf...
    size_bytes          BIGINT,
    checksum_sha256     CHAR(64),
    duration_seconds    INTEGER,                         -- chỉ cho video
    page_count          INTEGER,                         -- chỉ cho pdf
    upload_status       VARCHAR(20)   NOT NULL DEFAULT 'pending',
    uploaded_by         BIGINT,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_storage_objects_location UNIQUE (provider, bucket, object_key),
    CONSTRAINT ck_storage_objects_provider CHECK (provider IN ('s3', 'minio', 'gcs', 'azure')),
    CONSTRAINT ck_storage_objects_status   CHECK (upload_status IN ('pending', 'ready', 'failed', 'deleted')),
    CONSTRAINT ck_storage_objects_size     CHECK (size_bytes IS NULL OR size_bytes >= 0),
    CONSTRAINT fk_storage_objects_uploader FOREIGN KEY (uploaded_by) REFERENCES users (id) ON DELETE SET NULL
);
CREATE INDEX ix_storage_objects_uploader ON storage_objects (uploaded_by);

-- -----------------------------------------------------------------------------
-- 3. KHÓA HỌC & BÀI HỌC
-- -----------------------------------------------------------------------------
CREATE TABLE courses (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                VARCHAR(50)   NOT NULL,          -- mã khóa, dùng cho URL/tra cứu: py-101
    title               VARCHAR(255)  NOT NULL,
    short_description   VARCHAR(500),
    description         TEXT,
    thumbnail_object_id BIGINT,
    status              VARCHAR(20)   NOT NULL DEFAULT 'draft',
    published_at        TIMESTAMP WITH TIME ZONE,
    created_by          BIGINT        NOT NULL,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at          TIMESTAMP WITH TIME ZONE,        -- soft delete
    CONSTRAINT uq_courses_code     UNIQUE (code),
    CONSTRAINT ck_courses_status   CHECK (status IN ('draft', 'published', 'archived')),
    CONSTRAINT fk_courses_thumb    FOREIGN KEY (thumbnail_object_id) REFERENCES storage_objects (id) ON DELETE SET NULL,
    CONSTRAINT fk_courses_creator  FOREIGN KEY (created_by) REFERENCES users (id)
);
CREATE INDEX ix_courses_status     ON courses (status);
CREATE INDEX ix_courses_created_by ON courses (created_by);

-- Giảng viên phụ trách khóa (cho phép đồng giảng dạy). Phân quyền CRUD
-- khóa/bài học/học viên dựa vào bảng này, không chỉ dựa vào courses.created_by.
CREATE TABLE course_instructors (
    course_id       BIGINT      NOT NULL,
    user_id         BIGINT      NOT NULL,
    instructor_role VARCHAR(20) NOT NULL DEFAULT 'owner',
    assigned_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_course_instructors PRIMARY KEY (course_id, user_id),
    CONSTRAINT ck_course_instructors_role CHECK (instructor_role IN ('owner', 'co_instructor', 'assistant')),
    CONSTRAINT fk_course_instructors_course FOREIGN KEY (course_id) REFERENCES courses (id) ON DELETE CASCADE,
    CONSTRAINT fk_course_instructors_user   FOREIGN KEY (user_id)   REFERENCES users (id)   ON DELETE CASCADE
);
CREATE INDEX ix_course_instructors_user ON course_instructors (user_id);

-- Bài học: video | pdf -> trỏ tới storage_objects; quiz -> chi tiết ở bảng quizzes.
-- Quiz được coi là một "bài học" để tiến độ học tính thống nhất trên 1 bảng.
CREATE TABLE lessons (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id           BIGINT        NOT NULL,
    title               VARCHAR(255)  NOT NULL,
    description         TEXT,
    lesson_type         VARCHAR(20)   NOT NULL,
    media_object_id     BIGINT,
    sort_order          INTEGER       NOT NULL DEFAULT 0,
    estimated_minutes   INTEGER,
    is_preview          BOOLEAN       NOT NULL DEFAULT FALSE,   -- cho xem thử khi chưa ghi danh
    status              VARCHAR(20)   NOT NULL DEFAULT 'draft',
    created_by          BIGINT,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at          TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_lessons_type   CHECK (lesson_type IN ('video', 'pdf', 'quiz')),
    CONSTRAINT ck_lessons_status CHECK (status IN ('draft', 'published')),
    -- video/pdf phải có file; quiz thì không
    CONSTRAINT ck_lessons_media  CHECK (
        (lesson_type IN ('video', 'pdf') AND media_object_id IS NOT NULL)
        OR (lesson_type = 'quiz' AND media_object_id IS NULL)
    ),
    CONSTRAINT fk_lessons_course  FOREIGN KEY (course_id)       REFERENCES courses (id) ON DELETE CASCADE,
    CONSTRAINT fk_lessons_media   FOREIGN KEY (media_object_id) REFERENCES storage_objects (id),
    CONSTRAINT fk_lessons_creator FOREIGN KEY (created_by)      REFERENCES users (id) ON DELETE SET NULL
);
CREATE INDEX ix_lessons_course_order ON lessons (course_id, sort_order);
CREATE INDEX ix_lessons_media        ON lessons (media_object_id);

-- -----------------------------------------------------------------------------
-- 4. QUIZ
-- -----------------------------------------------------------------------------
-- Quan hệ 1-1 với lessons (lesson_type = 'quiz')
CREATE TABLE quizzes (
    lesson_id           BIGINT       NOT NULL PRIMARY KEY,
    pass_score_percent  NUMERIC(5,2) NOT NULL DEFAULT 70,
    time_limit_seconds  INTEGER,                         -- NULL = không giới hạn
    max_attempts        INTEGER,                         -- NULL = không giới hạn
    shuffle_questions   BOOLEAN      NOT NULL DEFAULT FALSE,
    show_correct_answers BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_quizzes_pass     CHECK (pass_score_percent BETWEEN 0 AND 100),
    CONSTRAINT ck_quizzes_attempts CHECK (max_attempts IS NULL OR max_attempts > 0),
    CONSTRAINT fk_quizzes_lesson   FOREIGN KEY (lesson_id) REFERENCES lessons (id) ON DELETE CASCADE
);

CREATE TABLE quiz_questions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id         BIGINT       NOT NULL,
    question_type   VARCHAR(20)  NOT NULL,
    content         TEXT         NOT NULL,
    explanation     TEXT,                                -- giải thích hiện sau khi nộp bài
    points          INTEGER      NOT NULL DEFAULT 1,
    sort_order      INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT ck_quiz_questions_type   CHECK (question_type IN ('single_choice', 'multiple_choice', 'true_false')),
    CONSTRAINT ck_quiz_questions_points CHECK (points >= 0),
    CONSTRAINT fk_quiz_questions_quiz   FOREIGN KEY (quiz_id) REFERENCES quizzes (lesson_id) ON DELETE CASCADE
);
CREATE INDEX ix_quiz_questions_quiz ON quiz_questions (quiz_id, sort_order);

CREATE TABLE quiz_options (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id     BIGINT        NOT NULL,
    content         VARCHAR(1000) NOT NULL,
    is_correct      BOOLEAN       NOT NULL DEFAULT FALSE,
    sort_order      INTEGER       NOT NULL DEFAULT 0,
    -- Cho phép FK ghép từ quiz_attempt_answers để đảm bảo đáp án thuộc đúng câu hỏi
    CONSTRAINT uq_quiz_options_id_question UNIQUE (id, question_id),
    CONSTRAINT fk_quiz_options_question FOREIGN KEY (question_id) REFERENCES quiz_questions (id) ON DELETE CASCADE
);
CREATE INDEX ix_quiz_options_question ON quiz_options (question_id, sort_order);

-- -----------------------------------------------------------------------------
-- 5. GHI DANH (học viên <-> khóa học)
--    "Xóa học viên khỏi khóa" = status 'removed' (giữ lịch sử tiến độ/điểm);
--    thêm lại = cập nhật về 'active' trên chính bản ghi này.
-- -----------------------------------------------------------------------------
CREATE TABLE enrollments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id       BIGINT      NOT NULL,
    user_id         BIGINT      NOT NULL,
    status          VARCHAR(20) NOT NULL DEFAULT 'active',
    enrolled_by     BIGINT,                              -- giảng viên đã thêm học viên
    enrolled_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    due_at          TIMESTAMP WITH TIME ZONE,            -- hạn hoàn thành (khóa "cần học")
    completed_at    TIMESTAMP WITH TIME ZONE,
    removed_at      TIMESTAMP WITH TIME ZONE,
    removed_by      BIGINT,
    CONSTRAINT uq_enrollments_course_user UNIQUE (course_id, user_id),
    CONSTRAINT ck_enrollments_status CHECK (status IN ('active', 'completed', 'removed')),
    CONSTRAINT fk_enrollments_course      FOREIGN KEY (course_id)   REFERENCES courses (id) ON DELETE CASCADE,
    CONSTRAINT fk_enrollments_user        FOREIGN KEY (user_id)     REFERENCES users (id)   ON DELETE CASCADE,
    CONSTRAINT fk_enrollments_enrolled_by FOREIGN KEY (enrolled_by) REFERENCES users (id),
    CONSTRAINT fk_enrollments_removed_by  FOREIGN KEY (removed_by)  REFERENCES users (id)
);
CREATE INDEX ix_enrollments_user_status   ON enrollments (user_id, status);
CREATE INDEX ix_enrollments_course_status ON enrollments (course_id, status);

-- -----------------------------------------------------------------------------
-- 6. TIẾN ĐỘ HỌC
-- -----------------------------------------------------------------------------
CREATE TABLE lesson_progress (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                 BIGINT       NOT NULL,
    lesson_id               BIGINT       NOT NULL,
    status                  VARCHAR(20)  NOT NULL DEFAULT 'in_progress',
    progress_percent        NUMERIC(5,2) NOT NULL DEFAULT 0,
    last_position_seconds   INTEGER,                     -- video: vị trí xem gần nhất (resume)
    last_page               INTEGER,                     -- pdf: trang đọc gần nhất
    time_spent_seconds      INTEGER      NOT NULL DEFAULT 0,
    started_at              TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at            TIMESTAMP WITH TIME ZONE,
    updated_at              TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_lesson_progress_user_lesson UNIQUE (user_id, lesson_id),
    CONSTRAINT ck_lesson_progress_status  CHECK (status IN ('in_progress', 'completed')),
    CONSTRAINT ck_lesson_progress_percent CHECK (progress_percent BETWEEN 0 AND 100),
    CONSTRAINT fk_lesson_progress_user    FOREIGN KEY (user_id)   REFERENCES users (id)   ON DELETE CASCADE,
    CONSTRAINT fk_lesson_progress_lesson  FOREIGN KEY (lesson_id) REFERENCES lessons (id) ON DELETE CASCADE
);
CREATE INDEX ix_lesson_progress_lesson ON lesson_progress (lesson_id);

CREATE TABLE quiz_attempts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id         BIGINT       NOT NULL,
    user_id         BIGINT       NOT NULL,
    attempt_no      INTEGER      NOT NULL,
    status          VARCHAR(20)  NOT NULL DEFAULT 'in_progress',
    score           NUMERIC(7,2),                        -- tổng điểm đạt được
    max_score       NUMERIC(7,2),                        -- tổng điểm tối đa lúc làm bài
    score_percent   NUMERIC(5,2),
    passed          BOOLEAN,
    started_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    submitted_at    TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_quiz_attempts_no     UNIQUE (quiz_id, user_id, attempt_no),
    CONSTRAINT ck_quiz_attempts_status CHECK (status IN ('in_progress', 'submitted', 'expired')),
    CONSTRAINT fk_quiz_attempts_quiz   FOREIGN KEY (quiz_id) REFERENCES quizzes (lesson_id) ON DELETE CASCADE,
    CONSTRAINT fk_quiz_attempts_user   FOREIGN KEY (user_id) REFERENCES users (id)          ON DELETE CASCADE
);
CREATE INDEX ix_quiz_attempts_user ON quiz_attempts (user_id, quiz_id);

-- Mỗi dòng = 1 phương án học viên đã chọn (multiple_choice -> nhiều dòng/câu)
CREATE TABLE quiz_attempt_answers (
    attempt_id      BIGINT NOT NULL,
    question_id     BIGINT NOT NULL,
    option_id       BIGINT NOT NULL,
    answered_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_quiz_attempt_answers PRIMARY KEY (attempt_id, question_id, option_id),
    CONSTRAINT fk_qaa_attempt  FOREIGN KEY (attempt_id) REFERENCES quiz_attempts (id) ON DELETE CASCADE,
    CONSTRAINT fk_qaa_question FOREIGN KEY (question_id) REFERENCES quiz_questions (id),
    -- FK ghép: option_id bắt buộc thuộc question_id
    CONSTRAINT fk_qaa_option   FOREIGN KEY (option_id, question_id) REFERENCES quiz_options (id, question_id)
);
CREATE INDEX ix_qaa_question ON quiz_attempt_answers (question_id);
CREATE INDEX ix_qaa_option   ON quiz_attempt_answers (option_id, question_id);

-- -----------------------------------------------------------------------------
-- 7. VIEW tiến độ theo khóa (SQL chuẩn, chạy được trên mọi DBMS lớn)
--    Chỉ tính bài học đã publish và chưa bị xóa mềm.
-- -----------------------------------------------------------------------------
CREATE VIEW v_enrollment_progress AS
SELECT
    e.id                                                        AS enrollment_id,
    e.user_id,
    e.course_id,
    e.status                                                    AS enrollment_status,
    e.due_at,
    COUNT(l.id)                                                 AS total_lessons,
    SUM(CASE WHEN lp.status = 'completed' THEN 1 ELSE 0 END)    AS completed_lessons,
    CASE WHEN COUNT(l.id) = 0 THEN 0
         ELSE ROUND(100.0 * SUM(CASE WHEN lp.status = 'completed' THEN 1 ELSE 0 END) / COUNT(l.id), 2)
    END                                                         AS progress_percent,
    MAX(lp.updated_at)                                          AS last_activity_at
FROM enrollments e
LEFT JOIN lessons l
       ON l.course_id = e.course_id
      AND l.status = 'published'
      AND l.deleted_at IS NULL
LEFT JOIN lesson_progress lp
       ON lp.lesson_id = l.id
      AND lp.user_id = e.user_id
GROUP BY e.id, e.user_id, e.course_id, e.status, e.due_at;
